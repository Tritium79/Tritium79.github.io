"""Build-time CSS bundling.

将 data/settings.json 中 css_bundle.sources 列出的模块按顺序合并为单个入口文件
（默认 style.css），替代运行时的 @import 链，减少串行请求轮次。

- 源模块位于 assets/css/，使用绝对 /assets/... 引用资源，合并后路径不变。
- assets/fonts/lxgw/subset.css（相对 url）与 result.css 分包不在合并范围，
  分别由模板以独立 <link> 引入（result.css 为延迟加载）。
"""

from pathlib import Path

from config import ROOT_DIR
from data_loader import get_settings


_DEFAULT_OUTPUT = 'style.css'
_DEFAULT_SOURCES = [
    'assets/css/fonts.css',
    'assets/css/variables.css',
    'assets/css/prism.css',
    'assets/css/base.css',
    'assets/css/header.css',
    'assets/css/menu.css',
    'assets/css/main.css',
    'assets/css/components.css',
    'assets/css/code.css',
    'assets/css/footer.css',
    'assets/css/responsive-portrait.css',
]
_HEADER = '/* Generated by build/css_bundle.py — 由 assets/css/ 模块合并，请勿直接编辑。 */\n'


def _bundle_config():
    config = get_settings('css_bundle', {}) or {}
    sources = config.get('sources', _DEFAULT_SOURCES)
    output = config.get('output', _DEFAULT_OUTPUT)
    return [ROOT_DIR / str(source) for source in sources], ROOT_DIR / str(output)


def build_css_bundle(force=False):
    """Merge the configured CSS modules into the entry file when content changed."""
    sources, output = _bundle_config()

    parts = [_HEADER]
    for path in sources:
        if not path.exists():
            raise FileNotFoundError(f'CSS 源文件不存在: {path.relative_to(ROOT_DIR)}')
        content = path.read_text(encoding='utf-8').strip()
        parts.append(f'/* ==== {path.relative_to(ROOT_DIR).as_posix()} ==== */\n{content}\n')
    bundle = '\n'.join(parts)

    if not force and output.exists() and output.read_text(encoding='utf-8') == bundle:
        print(f'  {output.name}: 无变化，跳过')
        return False

    temporary_path = output.with_name(output.name + '.tmp')
    temporary_path.write_text(bundle, encoding='utf-8')
    temporary_path.replace(output)
    print(f'  {output.name}: 已合并 {len(sources)} 个 CSS 模块')
    return True
